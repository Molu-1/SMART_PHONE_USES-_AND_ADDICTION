ACCENT = ['#38bdf8','#a78bfa','#34d399','#fbbf24','#fb7185']
px.defaults.template = DARK

filter_columns = ['gender','Age_group','Screen_time_category','stress_level','Sleep_Health']
filter_controls = {}
for col in filter_columns:
    if col in df.columns:
        vals = sorted(df[col].dropna().astype(str).unique().tolist())
        filter_controls[col] = widgets.Dropdown(options=['All']+vals, value='All',
            description=col.replace('_',' ').title(),
            style={'description_width':'initial'},
            layout=widgets.Layout(width='31%', margin='4px'))

refresh = widgets.Button(description='Refresh dashboard', icon='refresh', button_style='info',
                         layout=widgets.Layout(width='210px', height='42px'))
output = widgets.Output()

def selected_data():
    d = df.copy()
    for col, control in filter_controls.items():
        if control.value != 'All': d = d[d[col].astype(str) == control.value]
    return d

def metric_card(label, value, note):
    return f"""<div style="background:linear-gradient(145deg,#172554,#111827);border:1px solid #334155;
    border-radius:16px;padding:18px 20px;min-width:175px;flex:1;box-shadow:0 8px 25px #02061755">
    <div style="color:#94a3b8;font-size:11px;letter-spacing:1px;text-transform:uppercase;font-weight:700">{label}</div>
    <div style="color:#f8fafc;font-size:29px;font-weight:800;margin:9px 0 4px">{value}</div>
    <div style="color:#64748b;font-size:11px">{note}</div></div>"""

def show_dashboard(_=None):
    with output:
        clear_output(wait=True)
        d = selected_data()
        if d.empty:
            display(HTML('<h3 style="color:#f87171">No data matches the selected filters.</h3>')); return
        n_users = d['user_id'].nunique() if 'user_id' in d else len(d)
        avg_screen = d['daily_screen_time_hours'].mean() if 'daily_screen_time_hours' in d else np.nan
        avg_sleep = d['sleep_hours'].mean() if 'sleep_hours' in d else np.nan
        poor_sleep = (d['Sleep_Health'].astype(str).str.contains('poor', case=False, na=False).mean()*100) if 'Sleep_Health' in d else np.nan
        cards = [
            metric_card('Records',f'{len(d):,}','Filtered dataset rows'),
            metric_card('Unique users',f'{n_users:,}','Distinct user IDs'),
            metric_card('Average screen time',f'{avg_screen:.2f} h' if pd.notna(avg_screen) else 'N/A','Hours per day'),
            metric_card('Average sleep',f'{avg_sleep:.2f} h' if pd.notna(avg_sleep) else 'N/A','Hours per day'),
            metric_card('Poor sleep share',f'{poor_sleep:.1f}%' if pd.notna(poor_sleep) else 'N/A','Based on Sleep_Health label')]
        display(HTML('<div style="display:flex;flex-wrap:wrap;gap:12px;margin:10px 0 22px">'+''.join(cards)+'</div>'))

        # Chart 1: screen-time category mix
        if 'Screen_time_category' in d:
            s = d['Screen_time_category'].value_counts(dropna=False).rename_axis('Category').reset_index(name='Users')
            fig = px.bar(s, x='Category', y='Users', color='Category', title='01 · Screen-time category mix', text='Users', color_discrete_sequence=ACCENT)
            fig.update_layout(showlegend=False); fig.show()

        # Chart 2: sleep health split
        if 'Sleep_Health' in d:
            s = d['Sleep_Health'].value_counts(dropna=False).rename_axis('Sleep health').reset_index(name='Records')
            fig = px.pie(s, names='Sleep health', values='Records', hole=.62, title='02 · Sleep health composition', color_discrete_sequence=ACCENT)
            fig.update_traces(textposition='inside', textinfo='percent+label'); fig.show()

        # Chart 3: daily screen vs sleep with trendline
        if {'daily_screen_time_hours','sleep_hours'}.issubset(d.columns):
            fig = px.scatter(d, x='daily_screen_time_hours', y='sleep_hours', color='stress_level' if 'stress_level' in d else None,
                hover_data=[c for c in ['user_id','age','gender'] if c in d], opacity=.72,
                title='03 · Screen time and sleep relationship', trendline='ols' if len(d)>2 else None,
                color_discrete_sequence=ACCENT)
            fig.update_layout(xaxis_title='Screen time (hours/day)', yaxis_title='Sleep (hours/day)'); fig.show()

        # Chart 4: activity time mix
        activity_cols = [c for c in ['social_media_hours','gaming_hours'] if c in d]
        if activity_cols:
            act = d[activity_cols].mean().rename_axis('Activity').reset_index(name='Average hours')
            act['Activity'] = act['Activity'].map({'social_media_hours':'Social media','gaming_hours':'Gaming'})
            fig = px.bar(act, x='Activity', y='Average hours', color='Activity', text_auto='.2f', title='04 · Average daily activity hours', color_discrete_sequence=ACCENT)
            fig.update_layout(showlegend=False); fig.show()

        # Chart 5: stress profile by age group
        if {'Age_group','stress_level'}.issubset(d.columns):
            cross = pd.crosstab(d['Age_group'], d['stress_level'], normalize='index')*100
            fig = px.bar(cross.reset_index().melt(id_vars='Age_group', var_name='Stress level', value_name='Share %'),
                x='Age_group', y='Share %', color='Stress level', barmode='stack', title='05 · Stress profile across age groups', color_discrete_sequence=ACCENT)
            fig.update_layout(yaxis_title='Share of records (%)'); fig.show()

        # Chart 6: average screen time by gender and age
        if {'gender','Age_group','daily_screen_time_hours'}.issubset(d.columns):
            g = d.groupby(['Age_group','gender'], observed=False)['daily_screen_time_hours'].mean().reset_index()
            fig = px.density_heatmap(g, x='gender', y='Age_group', z='daily_screen_time_hours', histfunc='avg',
                title='06 · Average screen time by age group and gender', color_continuous_scale='Teal')
            fig.show()

        # Compact insights table
        display(HTML('<h3 style="color:#e2e8f0">Quick insight table</h3>'))
        numeric = [c for c in ['daily_screen_time_hours','sleep_hours','social_media_hours','gaming_hours'] if c in d]
        if numeric: display(d[numeric].describe().round(2))
        if {'daily_screen_time_hours','sleep_hours'}.issubset(d.columns):
            corr = d['daily_screen_time_hours'].corr(d['sleep_hours'])
            display(HTML(f'<p style="color:#cbd5e1"><b>Screen-time / sleep correlation:</b> {corr:.3f}. This is an association, not proof of cause.</p>'))

refresh.on_click(show_dashboard)
filter_ui = widgets.HBox(list(filter_controls.values()), layout=widgets.Layout(flex_flow='row wrap'))
display(widgets.VBox([filter_ui, refresh, output]))
show_dashboard()

